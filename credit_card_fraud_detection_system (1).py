#Import libraries and supports
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (accuracy_score, f1_score, precision_score, recall_score)
from sklearn.preprocessing import StandardScaler

#Loading the dataset as a panda data frame
  #ccd -> Credit Card Data
ccd = pd.read_csv('/content/creditcard.csv.zip')

#Testing data set
ccd.head()

ccd.tail()

#The last two columns share important information
  # "Amount" indicates the $-value of the transaction
  # "Class" tells us whether the transaction is legitimate (0) or fraudulent (1)

#Data set information
ccd.info()

#Check the distribution of legitmitate vs. fraudulent transactions
ccd['Class'].value_counts()

#This is a highly imbalanced data set
  #284315 legitimate cases compared with only 492 fraudulent cases

#Seperating cases
legit = ccd[ccd.Class == 0]
fraud = ccd[ccd.Class == 1]

print(legit.shape)
print(fraud.shape)

#Key stats about the given data set
legit.Amount.describe()

fraud.Amount.describe()

#Compare values between both types of transactions
ccd.groupby('Class').mean()

#Seperating the Class column
x = ccd.drop(columns='Class', axis=1)
y = ccd['Class']

#Splitting data into training data & testing data
x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.2, stratify=y, random_state=2)

print(x.shape, x_train.shape, x_test.shape)

#Temporarily combining training information and Class labels
train_data = x_train.copy()
train_data['Class'] = y_train

# Separating legitimate and fraudulent training transactions
train_legit = train_data[train_data.Class == 0]
train_fraud = train_data[train_data.Class == 1]

#Apply under-sampling -> Take the same number of legitimate transactions as fradulent transactions
legit_sample = train_legit.sample(n=len(train_fraud),random_state=42)

# Combining the balanced training data frames
new_dataset = pd.concat([legit_sample, train_fraud], axis=0)

new_dataset['Class'].value_counts()

new_dataset.groupby('Class').mean()

# Separating the balanced training data (Class column) - For model training
x_train = new_dataset.drop(columns='Class', axis=1)
y_train = new_dataset['Class']

#Now, the training data is a balanced set, ready to be interpreted

print(x_train)

print(y_train)

#Model Training

# Standardizing the training and testing data
scaler = StandardScaler()

x_train_scaled = scaler.fit_transform(x_train)
x_test_scaled = scaler.transform(x_test)

# Logistic Regression
model = LogisticRegression(max_iter=1000)

# Training the model with standardized training data
model.fit(x_train_scaled, y_train)

#Model Evaluation

#Accuracy with training data
x_train_prediction = model.predict(x_train_scaled)
training_data_accuracy = accuracy_score(y_train, x_train_prediction)
train_f1 = f1_score(y_train, x_train_prediction)

#Accuracy with testing data
x_test_prediction = model.predict(x_test_scaled)
testing_data_accuracy = accuracy_score(y_test, x_test_prediction, )
test_recall = recall_score(y_test, x_test_prediction)

#Training Results
print(f"Accuracy on training data: {training_data_accuracy:.2%}")
print(f"Training F1 Score: {train_f1:.2%}\n")

#Testing Results
print(f"Accuracy on real testing data: {testing_data_accuracy:.2%}")
print(f"Recall on testing data: {test_recall:.2%}")

#Overall, the prediction accuracy from the training data is extremely close to the accuracy of the testing data
#Both data sets report a high accuracy, demonstrating the reliability of the model