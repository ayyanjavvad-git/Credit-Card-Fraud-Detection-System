#Import libraries and supports
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score

#Loading the dataset as a panda data frame
  #ccd -> Credit Card Data
ccd = pd.read_csv('/content/creditcard.csv.zip')

#Testing data set
ccd.head()

ccd.tail()

#The last two columns share important information
  # "Amount" indicates the $-value of the transaction
  # "Class" tells us whether the transaction is legitimate (0) or fraudulent (1)

#Data set information
ccd.info()

#Check the distribution of legitmitate vs. fraudulent transactions
ccd['Class'].value_counts()

#This is a highly imbalanced data set
  #284315 legitimate cases compared with only 492 fraudulent cases

#Seperating cases
legit = ccd[ccd.Class == 0]
fraud = ccd[ccd.Class == 1]

print(legit.shape)
print(fraud.shape)

#Key stats about the given data set
legit.Amount.describe()

fraud.Amount.describe()

#Compare values between both types of transactions
ccd.groupby('Class').mean()

#Use under-sampling to build a saple data set containing more reasonable/similar distributions of transaction types
  #This way, evaluation will be more accurate
  #Set number of fraudulent cases = 492
legit_sample = legit.sample(n=len(fraud)) #Take 492 random data points

#Concatenating both data frames
new_dataset = pd.concat([legit_sample, fraud], axis=0) #axis=0 -> In terms of rows
new_dataset.head() #Check first five rows

new_dataset.tail()

#Analyzing the "Class" column:
  #We can see that the bottom rows (Class = 1) represents the fraudulent cases
  #The top rows (Class = 0) represetns legitimate cases
  #This is because axia was set to 0 while concatenating

new_dataset['Class'].value_counts()

new_dataset.groupby('Class').mean()

#Splitting data (Class column)
x = new_dataset.drop(columns='Class', axis=1)
y = new_dataset['Class']

print(x)

print(y) #The class column

#Split data into Training Data & Testing Data
x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.2, stratify=y, random_state=2)
  #20% of data dedicated to training data

print(x.shape, x_train.shape, x_test.shape)

#Model Training

#Logisitic Regression
model = LogisticRegression()

#Training the model with Training Data
model.fit(x_train, y_train)

#Model Evaluation

#Accuracy with training data
x_train_prediction = model.predict(x_train)
training_data_accuracy = accuracy_score(x_train_prediction, y_train)

print(f"Accuracy on training data: {training_data_accuracy}")

#Accuracy with testing data
x_test_prediction = model.predict(x_test)
testing_data_accuracy = accuracy_score(x_test_prediction, y_test)

print(f"Accuracy on real testing data: {testing_data_accuracy}")

#Overall, the prediction accuracy from the training data is extremely close to the accuracy of the testing data
#Both data sets report a high accuracy, demonstrating the reliability of the model